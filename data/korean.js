function pickOthers(pool, exclude, n) {
  const cand = pool.filter(w => w !== exclude);
  const out = [];
  while (out.length < n && cand.length) {
    const i = Math.floor(Math.random() * cand.length);
    out.push(cand.splice(i, 1)[0]);
  }
  return out;
}

function buildMimicQuestions() {
  const qs = [];

  SOUND_PICS.forEach(([emoji, name, sound]) => {
    qs.push({
      type: 'choice',
      tag: '소리 흉내',
      prompt: `${name}은(는) 어떤 소리를 낼까요?`,
      visual: emoji,
      options: [sound, ...pickOthers(SOUND_WORDS, sound, 3)],
      answer: sound,
      speak: `${name}은 어떤 소리를 낼까요?`,
      hint: `${name}은(는) "${sound}" 하고 소리를 내요.`,
    });
  });

  SENTENCES.forEach(([emoji, sentence, answer, wrongs]) => {
    qs.push({
      type: 'choice',
      tag: '문장 완성',
      prompt: '빈칸에 알맞은 흉내 내는 말을 골라요.',
      visual: emoji,
      sentence,
      options: [answer, ...wrongs],
      answer,
      speak: sentence.replace('___', '무엇무엇'),
      hint: sentence.replace('___', answer),
    });
  });

  KIND_SOUND.forEach(w => {
    qs.push({
      type: 'choice',
      tag: '소리? 모양?',
      prompt: '이 말은 무엇을 흉내 낸 말일까요?',
      word: w,
      options: ['소리를 흉내 낸 말', '모양을 흉내 낸 말'],
      answer: '소리를 흉내 낸 말',
      keepOrder: true,
      speak: `${w}. 이 말은 무엇을 흉내 낸 말일까요?`,
      hint: `"${w}"은(는) 소리를 흉내 낸 말이에요.`,
    });
  });
  KIND_SHAPE.forEach(w => {
    qs.push({
      type: 'choice',
      tag: '소리? 모양?',
      prompt: '이 말은 무엇을 흉내 낸 말일까요?',
      word: w,
      options: ['소리를 흉내 낸 말', '모양을 흉내 낸 말'],
      answer: '모양을 흉내 낸 말',
      keepOrder: true,
      speak: `${w}. 이 말은 무엇을 흉내 낸 말일까요?`,
      hint: `"${w}"은(는) 모양이나 움직임을 흉내 낸 말이에요.`,
    });
  });

  MEANINGS.forEach(([w, meaning, wrongs]) => {
    qs.push({
      type: 'choice',
      tag: '뜻 알기',
      prompt: '이 말은 어떤 뜻일까요?',
      word: w,
      options: [meaning, ...wrongs],
      answer: meaning,
      speak: `${w}. 이 말은 어떤 뜻일까요?`,
      hint: `"${w}"은(는) ${meaning}이에요.`,
    });
  });

  return qs;
}

